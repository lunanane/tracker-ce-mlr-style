# Re-creates plinky_wavetable.h from Plinky's sw/Core/Src/wavetable.h (read only, untrusted: only the numbers are taken, nothing is
# run or included from it):   python -I wavetable_import.py <path to plinky's wavetable.h> <output plinky_wavetable.h>
# Plinky's table: 17 tables, each 9 octave levels of one cycle (512, 256, 128 ... 2 samples + 1 guard point = the first sample),
# int16, +-16384 nominal. Band limited per level (the highest harmonic of a level of n samples is n/2).
import re
import sys

src = open(sys.argv[1]).read()
tabs = [[int(x) for x in m.group(1).split(',') if x.strip()] for m in re.finditer(r'\{(-?\d[^{}]*)\}', src)]
assert len(tabs) == 17 and all(len(t) == 1031 for t in tabs)
out = []
out.append('''// Sequencer tracks mod - PolyForm Noncommercial 1.0.0 (see seqgen/LICENSE.md). The DATA below is from the Plinky firmware
// (plinky_public, sw/Core/Src/wavetable.h), MIT License, Copyright (c) the authors of the Plinky firmware; the licence text is in
// plinky_voice.h (kept with the code) and NOTICE.md. Generated by wavetable_import.py - do not edit by hand.
// 17 tables x 1031 int16 = 35054 bytes of flash. Per table the 9 octave levels follow each other (one cycle each, the last point of a
// level repeats its first sample so the interpolation needs no wrap): 512, 256, 128, 64, 32, 16, 8, 4, 2 samples (+1 each).
#pragma once
#include "plinky_params.h"
#include <stdint.h>

namespace plinkyvoice {

constexpr int kWtSize = 1031; // kWtTables (17) is in plinky_params.h
// the flash image holds exactly one copy (function local static of an inline function: shared by all translation units)
inline const int16_t* wtData()
{
    static const int16_t t[kWtTables * kWtSize] = {''')
flat = [v for t in tabs for v in t]
for i in range(0, len(flat), 16):
    out.append('        ' + ','.join(str(v) for v in flat[i:i + 16]) + ',')
out.append('''    };
    return t;
}

}  // namespace plinkyvoice''')
open(sys.argv[2], 'w', newline='\r\n').write('\n'.join(out) + '\n')
